"""Build the Word Radar data (server only). Run once:  python scripts/build_word_radar_data.py

1. Downloads a 10,000-word English list (no swear words).
2. Adds Sem 1 tech words (Python basics, HTML/CSS, Git and command line, number systems, GenAI basics).
3. Keeps words matching ^[a-z]{3,}$.
4. Embeds every word with MiniLM (sentence-transformers/all-MiniLM-L6-v2 via fastembed).
5. Writes api/_lib/word-radar-data.js: the word list and, per puzzle, each word's similarity to the secret (0-1).
   The API works out ranks and the top 10 from this. Never serve this file to the browser.

Needs: pip install fastembed
"""
import json, re, urllib.request
from pathlib import Path

import numpy as np
from fastembed import TextEmbedding

WORDS_URL = 'https://raw.githubusercontent.com/first20hours/google-10000-english/master/google-10000-english-usa-no-swears.txt'
PUZZLES = ['loop', 'memory', 'network']   # puzzle 1, 2, 3 (in this order)

TECH = """
python code coding program programmer variable variables function functions loop loops string strings list lists tuple tuples
dictionary dictionaries dict key value integer float boolean print input range index indexes slice syntax error errors bug bugs
debug debugger exception compiler interpreter keyword operator operators condition conditional else elif while break continue
return argument parameter module import library method object type types len append insert remove pop sort sorted
html css tag tags element attribute selector class flexbox flex grid tailwind margin padding border layout responsive div span
heading paragraph link image form button style stylesheet webpage website browser frontend
git github commit commits branch merge clone push pull repository repo terminal command shell folder directory file files path
binary decimal octal hexadecimal bit bits byte bytes bitwise shift nibble digit digits base number numbers
memory ram rom cpu processor storage disk hardware software computer laptop keyboard mouse monitor screen chip
network internet wifi router server client cloud protocol packet email website online offline download upload bandwidth
algorithm logic data database table record query output result value
prompt prompts token tokens model models chatbot chatgpt gemini claude assistant training dataset neural embedding generative
""".split()

out_path = Path(__file__).resolve().parent.parent / 'api' / '_lib' / 'word-radar-data.js'

print('Downloading word list...')
raw = urllib.request.urlopen(WORDS_URL, timeout=60).read().decode('utf-8').split()
ok = re.compile(r'^[a-z]{3,}$')
words, seen = [], set()
for w in raw + TECH + PUZZLES:
    w = w.strip().lower()
    if ok.match(w) and w not in seen:
        seen.add(w); words.append(w)
print(len(words), 'words')

print('Embedding (first run downloads the MiniLM model)...')
model = TextEmbedding('sentence-transformers/all-MiniLM-L6-v2')
vecs = np.array(list(model.embed(words, batch_size=256)), dtype=np.float32)
vecs /= np.linalg.norm(vecs, axis=1, keepdims=True)
ix = {w: i for i, w in enumerate(words)}

puzzles = []
for secret in PUZZLES:
    sim = vecs @ vecs[ix[secret]]
    sim = np.clip(sim, 0, 1)
    sim[ix[secret]] = 1.0
    order = np.argsort(-sim)
    top10 = [words[i] for i in order if words[i] != secret][:10]
    print(f'{secret}: top 10 = {", ".join(top10)}')
    puzzles.append({'secret': secret, 'sim': [round(float(x), 4) for x in sim]})

data = {'model': 'sentence-transformers/all-MiniLM-L6-v2', 'words': words, 'puzzles': puzzles}
out_path.write_text('// Generated by scripts/build_word_radar_data.py. Server only: never import this from the page.\n'
                    'export default ' + json.dumps(data, separators=(',', ':')) + ';\n', encoding='utf-8')
print('Wrote', out_path, f'({out_path.stat().st_size // 1024} KB)')
